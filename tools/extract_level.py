#!/usr/bin/env python3
"""Regenerate src/consts.rs from the upstream cart.

The level is a Lua table in the cart's code (`level={ [0]=0, ... }`), not in the
`__map__` section: it is board data, one byte per cell, 25 rows of 21 cells.

Usage, from the repo root:

    python3 tools/extract_level.py            # reads .p8, falls back to the .txt
    python3 tools/extract_level.py --check    # exit 1 if src/consts.rs is stale

The cart in assets/upstream/ is gitignored (it is "No License"), so this script
is the only way to rebuild the table: keep it working if the cart is re-exported.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

COLS = 21
ROWS = 25
P8 = Path("assets/upstream/bubblegum_spin.p8")
TXT = Path("assets/upstream/bubblegum_spin_code.txt")
OUT = Path("src/consts.rs")


def cart_lua() -> str:
    """The cart's Lua source, from the .p8 if present, else the text dump."""
    if P8.exists():
        text = P8.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n")
        return text.split("__lua__", 1)[1].split("__gfx__", 1)[0]
    text = TXT.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n")
    return text


def extract_level() -> list[int]:
    lua = cart_lua()
    start = lua.index("level={")
    end = lua.index("\n}", start)
    block = re.sub(r"--.*", "", lua[start:end])  # strip comments, incl. the [0]= line
    body = block.split("[0]=", 1)[1]  # key 0 is a dummy, real cells start at 1
    nums = [int(n) for n in re.findall(r"-?\d+", body)]
    if len(nums) != COLS * ROWS:
        sys.exit(f"expected {COLS * ROWS} level entries, found {len(nums)}")
    if max(nums) > 9:
        sys.exit("level values must be 0..9")
    return nums


def ascii_row(row: list[int]) -> str:
    glyph = {0: ".", 7: "W", 8: "8", 9: "9"}
    return "".join(glyph.get(v, "?") for v in row)


def render(nums: list[int]) -> str:
    rows = [nums[i * COLS : (i + 1) * COLS] for i in range(ROWS)]
    lines = [
        "//! Data tables taken from the cart.",
        "//!",
        "//! Generated by `tools/extract_level.py` from the upstream cart; do not edit",
        "//! by hand. The regression test at the bottom is what guards it.",
        "",
        "/// The cart's `level` table: 25 rows of 21 cells, row-major, one byte per",
        "/// cell. `0` is an empty cell, `9` and `7` are coloured gumballs (the cart",
        "/// recolours them randomly at load, so their value only matters as \"not",
        "/// empty\"), and `8` is the white anchor at cell 262.",
        "///",
        "/// Row comments show the shape as `.` empty, `W` the 7-wall, `9` gumball,",
        "/// `8` the anchor.",
        "pub const LEVEL: [u8; 525] = [",
    ]
    for r, row in enumerate(rows):
        values = ", ".join(f"{v:>2}" for v in row)
        lines.append(f"    // row {r:2d}: {ascii_row(row)}")
        lines.append(f"    {values},")
    lines.append("];")
    lines.append("")
    lines.append(TESTS)
    return "\n".join(lines) + "\n"


TESTS = """\
#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn level_has_the_carts_shape() {
        assert_eq!(LEVEL.len(), 525);
        assert_eq!(LEVEL[262], 8, "the white anchor must be at the centre cell");
        let nines = LEVEL.iter().filter(|&&v| v == 9).count();
        let sevens = LEVEL.iter().filter(|&&v| v == 7).count();
        let eights = LEVEL.iter().filter(|&&v| v == 8).count();
        let zeros = LEVEL.iter().filter(|&&v| v == 0).count();
        assert_eq!((nines, sevens, eights, zeros), (36, 24, 1, 464));
    }

    #[test]
    fn every_coloured_cell_is_inside_the_mass() {
        // The level is one connected blob: 61 cells, all within 176..=348.
        for (i, &v) in LEVEL.iter().enumerate() {
            if v != 0 {
                assert!((176..=348).contains(&i), "cell {i} is outside the blob");
            }
        }
    }

    #[test]
    fn rows_are_the_ascii_shape_from_the_plan() {
        let glyph = |v: u8| match v {
            0 => '.',
            7 => 'W',
            8 => '8',
            _ => '9',
        };
        let row = |r: usize| -> String { LEVEL[r * 21..(r + 1) * 21].iter().map(|&v| glyph(v)).collect() };
        assert_eq!(row(0), ".....................");
        assert_eq!(row(8), "........WWWWW........");
        assert_eq!(row(12), "......W9998999W......");
        assert_eq!(row(16), "........WWWWW........");
        assert_eq!(row(24), ".....................");
    }
}
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if src/consts.rs is stale")
    args = ap.parse_args()

    text = render(extract_level())
    if args.check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            sys.exit(f"{OUT} is stale; run python3 tools/extract_level.py")
        print(f"{OUT} is up to date")
        return
    OUT.write_text(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
